	<h2>Результат использования условного описания функции</h2>
	<?php

$var = 1;   // Вариант 1 – нормальное определение и вызов func1_uslopis()
	// $var = 2; // Вариант 2 – вызов неопределённой функции
	// $var = 3; // Вариант 3 – повторное определение func3_uslopis()

	function func_obichn()
	{
	    echo "Сработала func_obichn(), доступная сразу после запуска скрипта.<br><br>";
	}
	func_obichn();

	switch ($var) {
	    case 1:
	        if ($var == 1) {
	            echo "Прошёл вход в тело оператора if<br>";
	            echo "с первым условным описанием функции func1_uslopis().<br><br>";

	            function func1_uslopis()
	            {
	                echo "Данный фрагмент печати - результат работы func1_uslopis(),<br>";
	                echo "определённой в первый раз для 1-го варианта сценария.<br>";
	            }
	        }
	        func1_uslopis(); // Успешный вызов
	        break;

	    case 2:
	        if ($var == 2) {
	            echo "Прошёл вход в тело оператора if для 2-го варианта<br>";
	            echo "с первым условным описанием функции func2_uslopis().<br><br>";

	            function func2_uslopis()
	            {
	                echo "Данный фрагмент печати - результат работы func2_uslopis(),<br>";
	                echo "определённой в первый раз для 2-го варианта сценария.<br>";
	                echo "Далее вызывается функция func1_uslopis().<br>";
	                echo "Так как она в этом варианте не определяется,<br>";
	                echo "система сообщит о невозможности этого - смотри ниже!!!<br><br>";
	            }
	        }
	        func2_uslopis(); // Вызов определённой функции
	        func1_uslopis(); // ОШИБКА: функция не определена
	        break;

	    case 3:
	        if ($var == 3) {
	            echo "Прошёл вход в тело оператора if для 3-го варианта<br>";
	            echo "с первым условным описанием функции func3_uslopis().<br><br>";

	            function func3_uslopis()
	            {
	                echo "Данный фрагмент печати - результат работы func3_uslopis(),<br>";
	                echo "определённой в первый раз для 3-го варианта сценария.<br>";
	                echo "Далее будет сделана попытка вторичного определения<br>";
	                echo "той же функции. Так как это недопустимо,<br>";
	                echo "система должна сообщить о невозможности этого.<br><br>";
	            }
	        }
	        func3_uslopis(); // Первый вызов

	        if ($var == 3) {
	            echo "Прошёл вход в тело оператора if для 3-го варианта<br>";
	            echo "со вторым условным описанием функции func3_uslopis()<br>";
	            echo "система сообщает о невозможности этого - смотри ниже!!!<br><br>";

	            // ВТОРОЕ ОПРЕДЕЛЕНИЕ – вызовет фатальную ошибку
	            function func3_uslopis()
	            {
	                echo "A и B сидели на трубе.<br>";
	            }
	        }
	        break;
	}
	?>
